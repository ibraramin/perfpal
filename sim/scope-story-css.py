#!/usr/bin/env python3
"""Scope `sim/sim.css` to `#atlas-story` for the in-report player.

The standalone prototype (`sim/index.html` + `sim/sim.css`) keeps its global
stylesheet. `report.html` embeds the same player inside `#atlas-story`, so the
stylesheet must not leak into the report. This generator is deterministic and
is the only supported way to produce `sim/sim.report.css`:

    python3 sim/scope-story-css.py

Rules:
- `:root`, `html`, `body` become `#atlas-story`.
- every other selector is prefixed with `#atlas-story `.
- `@media` / `@supports` bodies are scoped recursively.
- `@keyframes` / `@font-face` / `@page` are emitted unchanged (names are
  already `sim-*` and do not collide with the report's `atlas-*` set).
- comments are stripped; whitespace is normalised to one rule per line.
"""
from __future__ import annotations

import re
from pathlib import Path

SCOPE = "#atlas-story"
SRC = Path(__file__).with_name("sim.css")
OUT = Path(__file__).with_name("sim.report.css")


def scope_selector(selector: str) -> str:
    selector = " ".join(selector.split())
    if not selector:
        return selector
    if selector in {":root", "html", "body", "html,body", "body,html"}:
        return SCOPE
    if selector == "*":
        return f"{SCOPE} *"
    if selector.startswith(SCOPE):
        return selector
    return f"{SCOPE} {selector}"


def scope_prelude(prelude: str) -> str:
    parts = [scope_selector(part) for part in prelude.split(",")]
    # `html, body` both collapse to the scope root; keep one.
    seen: list[str] = []
    for part in parts:
        if part and part not in seen:
            seen.append(part)
    return ",".join(seen)


def split_blocks(text: str):
    """Yield (prelude, body) for every top-level `{...}` block."""
    index = 0
    length = len(text)
    while index < length:
        open_brace = text.find("{", index)
        if open_brace < 0:
            return
        prelude = text[index:open_brace].strip()
        depth = 1
        cursor = open_brace + 1
        while cursor < length and depth:
            if text[cursor] == "{":
                depth += 1
            elif text[cursor] == "}":
                depth -= 1
            cursor += 1
        if depth:
            raise SystemExit("unbalanced braces in sim.css")
        yield prelude, text[open_brace + 1 : cursor - 1]
        index = cursor


def scope_css(text: str) -> str:
    out: list[str] = []
    for prelude, body in split_blocks(text):
        compact = " ".join(prelude.split())
        if compact.startswith("@media") or compact.startswith("@supports"):
            inner = scope_css(body)
            out.append(f"{compact}{{\n{inner}}}\n")
        elif compact.startswith(("@keyframes", "@font-face", "@page")):
            out.append(f"{compact}{{{body.strip()}}}\n")
        else:
            out.append(f"{scope_prelude(compact)}{{{body.strip()}}}\n")
    return "".join(out)


def main() -> None:
    text = re.sub(r"/\*.*?\*/", "", SRC.read_text(), flags=re.S)
    scoped = scope_css(text)
    header = (
        "/* Generated by sim/scope-story-css.py from sim/sim.css. Do not edit.\n"
        " * The standalone player keeps the unscoped sim/sim.css; report.html\n"
        " * embeds this scoped copy under #atlas-story (ADR-0014).\n"
        " */\n"
    )
    overrides = (
        "\n/* Embed overrides: the report section is not a full-viewport page. */\n"
        f"{SCOPE} .page{{height:auto;min-height:0;max-width:1400px;padding-left:0;padding-right:0}}\n"
        f"{SCOPE} .canvas-shell{{flex:0 0 auto;aspect-ratio:1400/718;height:auto;max-width:1400px;min-height:0}}\n"
        f"{SCOPE} #story-stage-host{{display:block;width:100%}}\n"
        f"{SCOPE} #stage{{display:block;width:100%;height:auto}}\n"
        f"{SCOPE} details.s4-detail{{display:block;padding:0 12px 18px}}\n"
        f"{SCOPE} details.s4-detail[open]{{display:flex;flex-direction:column;gap:10px}}\n"
        f"{SCOPE} details.s4-detail>summary.s4-summary{{cursor:pointer;list-style:revert;margin:0 0 8px;padding:6px 8px;border:1px dashed var(--line);border-radius:4px;font-size:9px;font-weight:700;color:var(--muted);background:var(--card-2)}}\n"
        f"{SCOPE} details.s4-detail>summary.s4-summary:hover{{border-color:var(--hot);color:var(--ink)}}\n"
    )
    OUT.write_text(header + scoped + overrides)


if __name__ == "__main__":
    main()
