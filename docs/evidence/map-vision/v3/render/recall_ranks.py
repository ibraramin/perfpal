#!/usr/bin/env python3
"""Reproduce the V3 recall/rank table (map-idiom-ab.md section 4).

Builds the same RepoModel as the prototype generator, then records where each
pre-registered action lands in the full deterministic ordering and whether the
corresponding key view shows it inline. Writes recall_ranks.json and exits
non-zero if any rank drifts from the values recorded in the evidence doc.
"""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]  # .../docs/evidence/map-vision/v3/render
GEN = Path(__file__).resolve().parent / "generate_v3.py"
OUT = ROOT / "docs" / "evidence" / "map-vision" / "v3" / "recall_ranks.json"

TARGETS = [
    # repo, question, kind, selector, expected rank, total, inline
    ("tmux", "Q1", "finding", "PERF-C-CALL-002:input.c:969:1", 210, 7545, False),
    ("tmux", "Q2", "file", "tmux.h", 1, 216, True),
    ("tmux", "Q3", "func", "screen_write_collect_add|screen-write.c", 811, 3189, False),
    ("hyperfine", "Q1", "finding", "PERF-RS-ALLOC-001:src/benchmark/mod.rs:333:9", 197, 348, False),
    ("hyperfine", "Q2", "file", "src/command.rs", 4, 53, True),
    ("hyperfine", "Q3", "func", "execute_and_measure|src/timer/mod.rs", 66, 353, False),
    ("cJSON", "Q1", "finding", "PERF-C-CALL-002:cJSON.c:307:1", 35, 837, False),
    ("cJSON", "Q2", "file", "cJSON.h", 1, 101, True),
    ("cJSON", "Q3", "func", "cJSON_New_Item|cJSON.c", 58, 1055, False),
]

# Human labels from docs/evidence/map-vision-prereg.md, so the committed JSON is
# self-explanatory without opening the scan sources.
PREREG_LABELS = {
    ("tmux", "Q1"): "input_parse (input.c:969; pre-registration cites the parse path at :970)",
    ("tmux", "Q2"): "tmux.h (160 of 203 .c files include it)",
    ("tmux", "Q3"): "screen_write_collect_add (screen-write.c:2776; per-byte leaf)",
    ("hyperfine", "Q1"): "Benchmark::run (src/benchmark/mod.rs:346; loop :333-359)",
    ("hyperfine", "Q2"): "src/command.rs (substitution/quoting owner)",
    ("hyperfine", "Q3"): "execute_and_measure (src/timer/mod.rs:82; wall-clock wait)",
    ("cJSON", "Q1"): "parse_number (cJSON.c:357; function body from :307)",
    ("cJSON", "Q2"): "cJSON.h (public ABI)",
    ("cJSON", "Q3"): "cJSON_New_Item (cJSON.c:243; function body from :241)",
}


def load_generator():
    spec = importlib.util.spec_from_file_location("generate_v3", GEN)
    if spec is None or spec.loader is None:
        raise SystemExit(f"FATAL: cannot load {GEN}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    g = load_generator()
    models = {}
    results = []
    ok = True
    for repo, question, kind, selector, expected_rank, expected_total, expected_inline in TARGETS:
        if repo not in models:
            data, digest = g.load_repo(repo)
            models[repo] = g.RepoModel(repo, data, digest)
        model = models[repo]

        if kind == "finding":
            ids = [f["finding_id"] for f, _, _ in model.kv1_order]
            rank = ids.index(selector) + 1
            total = len(ids)
            inline = rank <= 5
            label = selector
        elif kind == "file":
            rank = model.kv2_order.index(selector) + 1
            total = len(model.kv2_order)
            inline = selector in [row["path"] for row in model.kv2_inline()]
            label = selector
        else:
            name, path = selector.split("|", 1)
            matches = [f for f in model.kv3_order if f["name"] == name and f["path"] == path]
            if not matches:
                raise SystemExit(f"FATAL: {repo} Q3 target {name} in {path} not found")
            func = matches[0]
            funcs = model.kv3_order
            rank = funcs.index(func) + 1
            total = len(funcs)
            selected = [row["func"]["name"] + "|" + row["func"]["path"] for row in model.kv3_selection()]
            inline = (name + "|" + path) in selected
            label = f"{name}|{path}"

        entry = {
            "repo": repo,
            "question": question,
            "kind": kind,
            "target": label,
            "prereg_label": PREREG_LABELS[(repo, question)],
            "rank": rank,
            "total": total,
            "inline": inline,
        }
        results.append(entry)
        if (rank, total, inline) != (expected_rank, expected_total, expected_inline):
            ok = False
            print(
                f"MISMATCH {repo} {question}: got {rank}/{total} inline={inline}, "
                f"expected {expected_rank}/{expected_total} inline={expected_inline}"
            )

    payload = {
        "_comment": "V3 recall/rank table reproducer. Generated by recall_ranks.py from the same RepoModel as the prototype generator; ranks are positions in the full deterministic ordering documented in prereg.md section 3 (as corrected).",
        "generated": "2026-10-21",
        "ranks": results,
    }
    OUT.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if not ok:
        return 1
    print(f"RECALL RANKS OK: {len(results)}/9 match map-idiom-ab.md section 4 -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
